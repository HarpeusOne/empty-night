"""Procedural textures for the house archetypes: breeze blocks (unfinished houses), corrugated roof sheet,
garage door, shop front.

Original work generated by this script (no photo pixels). Entries merged into art/manifest.json.
Usage: python3 tools/art/gen_building_textures.py
"""
import json, pathlib, random, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import gen_textures as G
from gen_textures import Noise, mul, mix


def breeze(seed):
    """Grey cinder blocks with mortar joints and damp patches. 128 px = 3 m of wall (WALL_TILE)."""
    rng = random.Random(seed)
    n = Noise(128, 5, 5, seed + 1)
    rows, cols = 12, 6          # blocks 0.25 m high, 0.5 m long
    tone = {}
    def fn(x, y):
        rh = 128 // rows + (1 if y >= 128 // rows * rows else 0)
        r = min(y // (128 // rows), rows - 1)
        cw = 128 // cols
        sx = (x + (cw // 2 if r % 2 else 0)) % 128
        c = sx // cw
        if (r, c) not in tone:
            tone[(r, c)] = 0.85 + rng.random() * 0.25
        lx, ly = sx % cw, y % (128 // rows)
        if lx < 1 or ly < 1:
            return (96, 94, 88)
        f = tone[(r, c)] * (0.9 + 0.25 * n.at(x, y)) + (rng.random() - 0.5) * 0.12
        return mul(mix((150, 150, 146), (120, 126, 112), n.at(x * 2 % 128, y) * 0.5), f)
    return fn


def roof_sheet(seed):
    """Dull grey corrugated sheet (eternit / blacha), streaked with rust and moss. 128 px = 2 m (ROOF_TILE)."""
    rng = random.Random(seed)
    n1, n2 = Noise(128, 3, 8, seed + 1), Noise(128, 10, 10, seed + 2)
    def fn(x, y):
        wave = 0.82 + 0.18 * abs(((x % 12) / 6.0) - 1.0)
        streak = 0.85 + 0.3 * n1.at(x, y)
        base = mix((122, 124, 124), (110, 92, 70), max(0.0, n2.at(x, y) - 0.55) * 1.6)
        return mul(base, wave * streak + (rng.random() - 0.5) * 0.06)
    return fn


def garage_door(seed):
    """Steel up-and-over garage door, horizontal ribs, faded green. Whole texture = one door."""
    rng = random.Random(seed)
    n = Noise(64, 4, 4, seed + 1)
    def fn(x, y):
        if x < 2 or x > 61 or y < 2:
            return (52, 52, 50)
        rib = 0.8 if y % 8 < 2 else 1.0
        return mul((92, 108, 96), rib * (0.85 + 0.25 * n.at(x, y)) + (rng.random() - 0.5) * 0.06)
    return fn


def shopfront(seed):
    """Dark shop window with an aluminium frame and a pale sign band at the top. Whole texture = one window."""
    rng = random.Random(seed)
    n = Noise(64, 3, 3, seed + 1)
    def fn(x, y):
        if y < 12:
            return mul((176, 170, 150), 0.9 + 0.15 * n.at(x, y))
        if x < 3 or x > 60 or y < 15 or y > 60 or 30 <= x <= 32:
            return (150, 152, 154)
        f = 0.7 + 0.5 * n.at(x, y) + (0.25 if (x - y) % 40 < 4 else 0.0)
        return mul((38, 44, 50), f + (rng.random() - 0.5) * 0.05)
    return fn


def main():
    spec = [("b_breeze", 128, 41, breeze), ("b_roof_sheet", 128, 43, roof_sheet),
            ("b_garage", 64, 45, garage_door), ("b_shopfront", 64, 47, shopfront)]
    for name, size, seed, fn in spec:
        G.build(name, size, size, fn(seed))
    manifest_path = G.ROOT / "art/manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    images = [e for e in manifest["images"] if not e["file"].split("/")[-1].startswith("b_")]
    for name, size, seed, _ in spec:
        images.append({"file": f"art/textures/{name}.png", "size": [size, size], "source": "procedural",
                       "generator": "tools/art/gen_building_textures.py", "seed": seed,
                       "license": "original work, generated by project code; no third-party image data",
                       "created": "2026-11-08"})
    manifest["images"] = images
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")
    print("building textures:", len(spec), "| manifest entries:", len(images))


if __name__ == "__main__":
    main()
