"""Procedural textures for the church grounds: grey cobble setts, picket fence (with cut-out gaps), dark conifer needles.

Original work generated by this script (no photo pixels). Entries merged into art/manifest.json.
Usage: python3 tools/art/gen_grounds_textures.py
"""
import json, math, pathlib, random, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import gen_textures as G
from gen_textures import Noise, mul, mix
from PIL import Image


def cobble(seed):
    """Grey granite setts laid in staggered rows (128 px = 1 m of paving at tile 1.0)."""
    rng = random.Random(seed)
    n = Noise(128, 6, 6, seed + 1)
    rows, cols = 8, 8
    tone = {}
    def fn(x, y):
        rh = 128 // rows
        r = y // rh
        off = (rh if r % 2 else 0) // 1
        cw = 128 // cols
        c = ((x + (cw // 2 if r % 2 else 0)) % 128) // cw
        key = (r, c)
        if key not in tone:
            tone[key] = 0.78 + rng.random() * 0.4
        lx = (x + (cw // 2 if r % 2 else 0)) % cw
        ly = y % rh
        if lx < 1 or ly < 1:
            return (70, 70, 72)
        f = tone[key] * (1 + (n.at(x, y) - 0.5) * 0.25 + (rng.random() - 0.5) * 0.08)
        base = mix((128, 128, 130), (140, 126, 120), (tone[key] * 3) % 1.0)
        return mul(base, f)
    return fn


def picket(seed):
    """RGBA: dark wooden pickets with gaps (alpha 0) and two horizontal rails. 64 px = 1 m wide, 64 px = 1 m high."""
    rng = random.Random(seed)
    grain = Noise(64, 2, 14, seed + 1)
    def fn(x, y):
        slat = x % 8
        ys = y
        rail = (8 <= ys < 14) or (46 <= ys < 52)
        # picket tops are pointed
        px = x // 8
        top = 3 + (px * 5 + seed) % 3
        is_slat = 1 <= slat <= 6 and ys >= top
        if slat in (3, 4) and ys < top + 3:
            is_slat = ys >= top - 1
        if not (is_slat or rail):
            return (0, 0, 0, 0)
        f = 0.55 + 0.45 * grain.at(x, y) + (rng.random() - 0.5) * 0.08
        c = mul((74, 52, 36), f) if is_slat else mul((58, 42, 30), f)
        return (c[0], c[1], c[2], 255)
    return fn


def conifer(seed):
    """Dark blue-green needles (thuja / yew)."""
    rng = random.Random(seed)
    n1, n2 = Noise(64, 4, 4, seed + 1), Noise(64, 12, 12, seed + 2)
    def fn(x, y):
        f = 0.55 + 0.7 * n1.at(x, y) * (0.7 + 0.5 * n2.at(x, y)) + (rng.random() - 0.5) * 0.2
        return mul((34, 62, 40), f)
    return fn


def save_rgba(name, w, h, fn):
    img = Image.new("RGBA", (w, h))
    img.putdata([fn(x, y) for y in range(h) for x in range(w)])
    img.save(G.OUT / f"{name}.png", optimize=True)


def main():
    G.build("g_cobble", 128, 128, cobble(31))
    G.build("g_conifer", 64, 64, conifer(33))
    save_rgba("g_picket", 64, 64, picket(35))
    spec = [("g_cobble", 128, 31), ("g_picket", 64, 35), ("g_conifer", 64, 33)]
    manifest_path = G.ROOT / "art/manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    images = [e for e in manifest["images"] if not e["file"].split("/")[-1].startswith("g_")]
    for name, size, seed in spec:
        images.append({"file": f"art/textures/{name}.png", "size": [size, size], "source": "procedural",
                       "generator": "tools/art/gen_grounds_textures.py", "seed": seed,
                       "license": "original work, generated by project code; no third-party image data",
                       "created": "2026-11-07"})
    manifest["images"] = images
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")
    print("grounds textures:", len(spec), "| manifest entries:", len(images))


if __name__ == "__main__":
    main()
