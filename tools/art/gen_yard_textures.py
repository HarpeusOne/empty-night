"""Procedural textures for the school yard props (2026-11-08): the mint-green paint of the metal fences and the
gate, their chain-link mesh (cut-out), a flower bed (cut-out), bare twigs of pollarded trees (cut-out), the
artificial turf of the pitch and the goal net (cut-out).

Original work generated by this script (no photo pixels). Entries merged into art/manifest.json (prefix y_).
Usage: python3 tools/art/gen_yard_textures.py
"""
import json, math, pathlib, random, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import gen_textures as G
from gen_textures import Noise, mul, mix
from PIL import Image, ImageDraw

PAINT = (72, 150, 118)          # the faded mint green of the photos


def paint(seed):
    """Faded mint-green paint on steel, with worn and rusty spots. 64 px = 1 m."""
    rng = random.Random(seed)
    n, spots = Noise(64, 4, 4, seed + 1), Noise(64, 14, 14, seed + 2)
    def fn(x, y):
        c = mul(PAINT, 0.82 + 0.26 * n.at(x, y) + (rng.random() - 0.5) * 0.06)
        s = spots.at(x, y)
        if s > 0.86:
            c = mix(c, (118, 82, 58), min(0.7, (s - 0.86) * 6))   # rust
        elif s < 0.08:
            c = mix(c, (150, 156, 150), 0.4)                       # paint worn to grey zinc
        return c
    return fn


def chainlink(seed):
    """RGBA: green plastic-coated chain-link mesh, diamonds 8 px (64 px = 1 m: a 12.5 cm mesh), alpha 0 in the holes."""
    rng = random.Random(seed)
    def fn(x, y):
        a = (x + y) % 8
        b = (x - y) % 8
        if a in (0, 1, 2) or b in (0, 1, 2):         # 3 px wires: >50% cover, so the mesh stays visible in the mipmaps
            f = 0.75 + 0.35 * rng.random()
            c = mul(PAINT, f)
            return (c[0], c[1], c[2], 255)
        return (0, 0, 0, 0)
    return fn


def flowers(seed):
    """RGBA: a strip of low bedding flowers seen from the side: green stems and leaves, round heads in red, yellow,
    white, purple; transparent above. 64 x 64 px = 1 m wide, 0.5 m high."""
    rng = random.Random(seed)
    img = Image.new("RGBA", (64, 64), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    for _ in range(70):                                   # leaves and stems
        x = rng.randrange(64)
        top = rng.randrange(18, 50)
        g = mul((52, 92, 44), 0.7 + 0.5 * rng.random())
        d.line([(x, 63), (x + rng.randint(-3, 3), top)], fill=g + (255,), width=2)
        d.ellipse([x - 3, top + 4, x + 3, top + 9], fill=g + (255,))
    heads = [(178, 38, 44), (214, 176, 52), (226, 222, 210), (120, 66, 140), (200, 92, 120)]
    for _ in range(30):
        x = rng.randrange(2, 62)
        y = rng.randrange(12, 40)
        c = mul(rng.choice(heads), 0.8 + 0.3 * rng.random())
        r = rng.choice((2, 3, 3, 4))
        d.ellipse([x - r, y - r, x + r, y + r], fill=c + (255,))
    for x in range(64):                                   # soil showing at the foot
        for y in range(58, 64):
            if rng.random() < 0.5:
                img.putpixel((x, y), mul((66, 52, 40), 0.8 + 0.4 * rng.random()) + (255,))
    return img


def twigs(seed):
    """RGBA: the bare shoots of a pollarded tree's knob: thin grey-brown rods fanning up from the bottom middle,
    transparent around them. 64 x 64 px."""
    rng = random.Random(seed)
    img = Image.new("RGBA", (64, 64), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    for _ in range(26):
        x0 = 32 + rng.randint(-6, 6)
        ang = math.radians(rng.uniform(-60, 60))
        length = rng.uniform(30, 62)
        x1 = x0 + math.sin(ang) * length
        y1 = 63 - math.cos(ang) * length
        c = mul((84, 74, 66), 0.7 + 0.5 * rng.random())
        d.line([(x0, 63), (x1, y1)], fill=c + (255,), width=1 if rng.random() < 0.6 else 2)
        if rng.random() < 0.5:                          # a side shoot
            xm = (x0 + x1) / 2
            ym = (63 + y1) / 2
            a2 = ang + math.radians(rng.choice((-30, 30)))
            d.line([(xm, ym), (xm + math.sin(a2) * length * 0.35, ym - math.cos(a2) * length * 0.35)],
                   fill=c + (255,), width=1)
    return img


def turf(seed):
    """Artificial turf: green with mowing-like stripes along x and grain. 128 px = 4 m (tile 4)."""
    rng = random.Random(seed)
    n = Noise(128, 8, 8, seed + 1)
    def fn(x, y):
        stripe = 1.06 if (x // 32) % 2 == 0 else 0.94
        f = stripe * (0.86 + 0.2 * n.at(x, y) + (rng.random() - 0.5) * 0.12)
        return mul((58, 108, 58), f)
    return fn


def net(seed):
    """RGBA: white goal net, 10 cm squares (64 px = 1 m), slightly irregular, alpha 0 in the holes."""
    rng = random.Random(seed)
    def fn(x, y):
        if x % 6 in (0, 1) or y % 6 in (0, 1):       # >50% cover: still visible far away (mipmaps)
            g = int(200 + 40 * rng.random())
            return (g, g, g, 255)
        return (0, 0, 0, 0)
    return fn


def save_rgba(name, w, h, fn):
    img = Image.new("RGBA", (w, h))
    img.putdata([fn(x, y) for y in range(h) for x in range(w)])
    img.save(G.OUT / f"{name}.png", optimize=True)


def main():
    G.build("y_paint", 64, 64, paint(91))
    G.build("y_turf", 128, 128, turf(97))
    save_rgba("y_chainlink", 64, 64, chainlink(93))
    save_rgba("y_net", 64, 64, net(99))
    flowers(95).save(G.OUT / "y_flowers.png", optimize=True)
    twigs(101).save(G.OUT / "y_twigs.png", optimize=True)
    spec = [("y_paint", 64, 91), ("y_turf", 128, 97), ("y_chainlink", 64, 93), ("y_net", 64, 99),
            ("y_flowers", 64, 95), ("y_twigs", 64, 101)]
    manifest_path = G.ROOT / "art/manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    images = [e for e in manifest["images"] if not e["file"].split("/")[-1].startswith("y_")]
    for name, size, seed in spec:
        images.append({"file": f"art/textures/{name}.png", "size": [size, size], "source": "procedural",
                       "generator": "tools/art/gen_yard_textures.py", "seed": seed,
                       "license": "original work, generated by project code; no third-party image data",
                       "created": "2026-11-08"})
    manifest["images"] = images
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")
    print("yard textures:", len(spec), "| manifest entries:", len(images))


if __name__ == "__main__":
    main()
