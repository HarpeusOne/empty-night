"""Procedural textures for the school (key building 2, 2026-11-08): white-framed windows of the new wing and the
gym, the old school's windows, the gym's stepped glazing, the brown framed glass doors, clean ribbed sheet metal
(the arched roofs and the beige cladding of the gym gable, tinted in the material) and smooth light plaster.

Original work generated by this script (no photo pixels). Entries merged into art/manifest.json (prefix s_).
Usage: python3 tools/art/gen_school_textures.py
"""
import json, pathlib, random, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import gen_textures as G
from gen_textures import Noise, mul, mix

GLASS_TOP = (58, 74, 92)
GLASS_BOT = (30, 38, 50)
FRAME = (236, 236, 232)


def _glass(x, y, h, rng, n):
    t = y / float(h)
    c = mix(GLASS_TOP, GLASS_BOT, t)
    if (x + y) % 23 < 3:                                  # a faint diagonal reflection
        c = mix(c, (120, 140, 160), 0.25)
    return mul(c, 0.92 + 0.12 * n.at(x, y) + (rng.random() - 0.5) * 0.04)


def window_new(seed):
    """Window of the new wing / the gym: white PVC frame, a transom on top and three tall sashes. Whole texture
    = the whole window (stretched over it). 64 x 96 px."""
    rng = random.Random(seed)
    n = Noise(64, 4, 4, seed + 1)
    def fn(x, y):
        if x < 3 or x > 60 or y < 3 or y > 92:
            return FRAME
        if 28 <= y <= 31:                                 # transom bar
            return FRAME
        if y > 31 and (x in (21, 22, 41, 42)):
            return FRAME
        if y < 28 and x in (31, 32):
            return FRAME
        return _glass(x, y, 96, rng, n)
    return fn


def window_old(seed):
    """Window of the old white school: white frame, two sashes with a top light, a grey sill. 64 x 64 px."""
    rng = random.Random(seed)
    n = Noise(64, 4, 4, seed + 2)
    def fn(x, y):
        if y > 58:
            return (170, 172, 172)                        # sill
        if x < 3 or x > 60 or y < 3 or y > 57:
            return FRAME
        if 20 <= y <= 22 or x in (31, 32):
            return FRAME
        return _glass(x, y, 64, rng, n)
    return fn


def glazing(seed):
    """Grid of the gym gable glazing: square panes in white frames. 1 tile = 1 pane (repeat it)."""
    rng = random.Random(seed)
    n = Noise(32, 3, 3, seed + 3)
    def fn(x, y):
        if x < 2 or x > 29 or y < 2 or y > 29:
            return FRAME
        c = mix((150, 170, 186), (96, 116, 134), y / 32.0)  # the sky shows in it, lighter than the windows
        return mul(c, 0.92 + 0.12 * n.at(x, y) + (rng.random() - 0.5) * 0.03)
    return fn


def door(seed):
    """Double glass door in a red-brown aluminium frame. Whole texture = the doorway. 64 x 96 px."""
    rng = random.Random(seed)
    n = Noise(64, 4, 4, seed + 4)
    frame = (128, 54, 40)
    def fn(x, y):
        if x < 4 or x > 59 or y < 4:
            return frame
        if x in (30, 31, 32, 33):
            return frame
        if 56 <= y <= 59 or y > 88:
            return frame                                  # cross bar, kick plate
        if (x in (26, 27) or x in (36, 37)) and 46 <= y <= 52:
            return (190, 190, 186)                        # handles
        return _glass(x, y, 96, rng, n)
    return fn


def sheet(seed):
    """Clean standing-seam / ribbed sheet metal, light grey (tinted brown or beige in the material). Ribs run
    along v. 64 px = 1 m."""
    rng = random.Random(seed)
    n = Noise(64, 2, 8, seed + 5)
    def fn(x, y):
        r = x % 16
        f = 1.0
        if r in (0, 1):
            f = 1.22                                      # rib top in the light
        elif r in (2, 3):
            f = 0.72                                      # its shadow
        elif r == 15:
            f = 0.9
        f *= 0.9 + 0.14 * n.at(x, y) + (rng.random() - 0.5) * 0.03
        return mul((176, 176, 172), f)
    return fn


def plaster(seed):
    """Smooth light plaster with slight streaks of dirt (tinted per wall). 128 px = 2 m."""
    rng = random.Random(seed)
    n1, n2 = Noise(128, 3, 3, seed + 6), Noise(128, 2, 12, seed + 7)
    def fn(x, y):
        f = 0.9 + 0.08 * n1.at(x, y) - 0.06 * max(0.0, n2.at(x, y) - 0.6) * (y / 128.0) + (rng.random() - 0.5) * 0.03
        return mul((226, 224, 218), f)
    return fn


def main():
    spec = [("s_window_new", 64, 96, 71, window_new), ("s_window_old", 64, 64, 73, window_old),
            ("s_glazing", 32, 32, 75, glazing), ("s_door", 64, 96, 77, door), ("s_sheet", 64, 64, 79, sheet),
            ("s_plaster", 128, 128, 81, plaster)]
    for name, w, h, seed, fn in spec:
        G.build(name, w, h, fn(seed))
    manifest_path = G.ROOT / "art/manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    images = [e for e in manifest["images"] if not e["file"].split("/")[-1].startswith("s_")]
    for name, w, h, seed, _ in spec:
        images.append({"file": f"art/textures/{name}.png", "size": [w, h], "source": "procedural",
                       "generator": "tools/art/gen_school_textures.py", "seed": seed,
                       "license": "original work, generated by project code; no third-party image data",
                       "created": "2026-11-08"})
    manifest["images"] = images
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")
    print("school textures:", len(spec), "| manifest entries:", len(images))


if __name__ == "__main__":
    main()
