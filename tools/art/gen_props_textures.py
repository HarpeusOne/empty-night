"""Procedural textures for the map props added on 2026-11-08: polished dark granite (gravestones), a rough
field boulder (the monument stone), painted metal (bins, notice board), the notice board face, the red glass of
a grave candle and a clipped box hedge.

Original work generated by this script (no photo pixels). Entries merged into art/manifest.json (prefix p_).
Usage: python3 tools/art/gen_props_textures.py
"""
import json, pathlib, random, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import gen_textures as G
from gen_textures import Noise, mul, mix


def granite(seed):
    """Polished dark grey granite with light and black specks, faint streaks. 128 px = 1 m."""
    rng = random.Random(seed)
    n1, n2 = Noise(128, 4, 4, seed + 1), Noise(128, 16, 16, seed + 2)
    def fn(x, y):
        f = 0.75 + 0.35 * n1.at(x, y) + 0.2 * n2.at(x, y)
        r = rng.random()
        if r < 0.05:
            return mul((150, 148, 146), 0.8 + 0.3 * rng.random())
        if r < 0.10:
            return (14, 14, 16)
        return mul((52, 52, 56), f)
    return fn


def boulder(seed):
    """Weathered pinkish-grey granite with mottled patches and lichen. 128 px = 1 m."""
    rng = random.Random(seed)
    n1, n2, n3 = Noise(128, 3, 3, seed + 1), Noise(128, 10, 10, seed + 2), Noise(128, 6, 6, seed + 3)
    def fn(x, y):
        base = mix((150, 118, 108), (118, 112, 110), n1.at(x, y))
        f = 0.72 + 0.4 * n2.at(x, y) + (rng.random() - 0.5) * 0.18
        c = mul(base, f)
        if n3.at(x, y) > 0.78:
            c = mix(c, (128, 132, 96), 0.45)           # lichen
        if rng.random() < 0.04:
            c = mul(c, 0.55)
        return c
    return fn


def metal(seed):
    """Dark green painted sheet metal, slightly worn. 64 px = 1 m."""
    rng = random.Random(seed)
    n, spots = Noise(64, 4, 4, seed + 1), Noise(64, 16, 16, seed + 2)
    def fn(x, y):
        f = 0.8 + 0.3 * n.at(x, y) + (rng.random() - 0.5) * 0.06
        c = mul((46, 70, 54), f)
        if spots.at(x, y) > 0.9:
            c = mix(c, (110, 80, 56), 0.5)             # a rust spot
        return c
    return fn


def notice(seed):
    """Front of a metal notice board: green frame, cork-coloured board, pinned white / yellow sheets.
    The whole texture is the whole board (stretched)."""
    rng = random.Random(seed)
    n = Noise(64, 6, 6, seed + 1)
    sheets = []
    for (sx, sy, w, h, col) in [(6, 7, 16, 21, (226, 224, 214)), (26, 6, 14, 18, (232, 222, 150)),
                                (44, 9, 14, 20, (220, 220, 222)), (8, 34, 18, 22, (216, 212, 200)),
                                (31, 30, 12, 15, (230, 230, 232)), (46, 36, 12, 19, (200, 214, 226))]:
        sheets.append((sx, sy, w, h, col))
    def fn(x, y):
        if x < 3 or x > 60 or y < 3 or y > 60:
            return mul((46, 70, 54), 0.85 + 0.2 * n.at(x, y))
        for (sx, sy, w, h, col) in sheets:
            if sx <= x < sx + w and sy <= y < sy + h:
                lx, ly = x - sx, y - sy
                if 2 <= lx < w - 2 and ly > 3 and ly % 3 == 0 and (lx * 7 + ly * 3) % 11 > 2:
                    return mul(col, 0.62)                # lines of text
                if lx == w // 2 and ly == 1:
                    return (180, 30, 30)               # pin
                return mul(col, 0.92 + 0.1 * n.at(x, y))
        return mul((150, 112, 72), 0.8 + 0.35 * n.at(x, y) + (rng.random() - 0.5) * 0.1)
    return fn


def candle_glass(seed):
    """Red glass of a grave candle (znicz): darker at the bottom, a vertical highlight. Whole texture = the side."""
    rng = random.Random(seed)
    def fn(x, y):
        f = 0.55 + 0.5 * (1.0 - y / 32.0) + (rng.random() - 0.5) * 0.05
        c = mul((170, 26, 22), f)
        if 6 <= x <= 8:
            c = mix(c, (240, 170, 160), 0.45)
        return c
    return fn


def box_hedge(seed):
    """Clipped privet / box hedge: dense small leaves, lighter on top. 64 px = 1 m."""
    rng = random.Random(seed)
    n1, n2 = Noise(64, 5, 5, seed + 1), Noise(64, 16, 16, seed + 2)
    def fn(x, y):
        f = 0.55 + 0.6 * n1.at(x, y) * (0.6 + 0.6 * n2.at(x, y)) + (rng.random() - 0.5) * 0.25
        return mul((58, 92, 44), f)
    return fn


def main():
    spec = [("p_granite", 128, 51, granite), ("p_boulder", 128, 53, boulder), ("p_metal", 64, 55, metal),
            ("p_notice", 64, 57, notice), ("p_candle", 32, 59, candle_glass), ("p_box_hedge", 64, 61, box_hedge)]
    for name, size, seed, fn in spec:
        G.build(name, size, size, fn(seed))
    manifest_path = G.ROOT / "art/manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    images = [e for e in manifest["images"] if not e["file"].split("/")[-1].startswith("p_")]
    for name, size, seed, _ in spec:
        images.append({"file": f"art/textures/{name}.png", "size": [size, size], "source": "procedural",
                       "generator": "tools/art/gen_props_textures.py", "seed": seed,
                       "license": "original work, generated by project code; no third-party image data",
                       "created": "2026-11-08"})
    manifest["images"] = images
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")
    print("props textures:", len(spec), "| manifest entries:", len(images))


if __name__ == "__main__":
    main()
