"""Procedural PS2-style textures (128 px or smaller, tileable) for the look gate. Dirty, damp, grey: a Polish village
in an overcast autumn, not a postcard.

Pure Python + Pillow, deterministic (fixed seeds). The images are original work generated by this script,
not derived from any third-party image, so there is no licence encumbrance. Every output is listed in
art/manifest.json (project rule: each generated image has a manifest entry).

Usage: python3 tools/art/gen_textures.py
"""
import json, math, pathlib, random
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "art/textures"


class Noise:
    """Tileable value noise on a cells_x * cells_y lattice."""
    def __init__(self, size, cells_x, cells_y, seed):
        rng = random.Random(seed)
        self.size, self.cx, self.cy = size, cells_x, cells_y
        self.lat = [[rng.random() for _ in range(cells_x)] for _ in range(cells_y)]

    def at(self, x, y):
        fx, fy = x / self.size * self.cx, y / self.size * self.cy
        ix, iy = int(fx), int(fy)
        tx, ty = fx - ix, fy - iy
        tx, ty = tx * tx * (3 - 2 * tx), ty * ty * (3 - 2 * ty)
        x0, x1, y0, y1 = ix % self.cx, (ix + 1) % self.cx, iy % self.cy, (iy + 1) % self.cy
        a = self.lat[y0][x0] * (1 - tx) + self.lat[y0][x1] * tx
        b = self.lat[y1][x0] * (1 - tx) + self.lat[y1][x1] * tx
        return a * (1 - ty) + b * ty


def clamp(v): return max(0, min(255, int(v)))
def mul(rgb, f): return tuple(clamp(c * f) for c in rgb)
def mix(a, b, t): return tuple(clamp(a[i] * (1 - t) + b[i] * t) for i in range(3))


def build(name, w, h, fn):
    img = Image.new("RGB", (w, h))
    img.putdata([fn(x, y) for y in range(h) for x in range(w)])
    img.save(OUT / f"{name}.png", optimize=True)


def plaster(seed, base, damp=(104, 112, 96)):
    """Weathered render: mottling, rain streaks running down, damp green-grey patches, flaking spots."""
    rng = random.Random(seed)
    n1, n2 = Noise(128, 4, 4, seed + 1), Noise(128, 16, 16, seed + 2)
    streak, wet, patch = Noise(128, 22, 2, seed + 3), Noise(128, 5, 5, seed + 4), Noise(128, 3, 3, seed + 5)
    def fn(x, y):
        f = 1 + (n1.at(x, y) - 0.5) * 0.36 + (n2.at(x, y) - 0.5) * 0.16 + (rng.random() - 0.5) * 0.07
        f *= 1 - max(0.0, streak.at(x, y) - 0.55) * 0.28         # faint rain streaks (strong ones read as siding)
        f *= 0.90 + patch.at(x, y) * 0.16                         # large uneven stains
        c = mul(base, f)
        w = wet.at(x, y)
        if w > 0.62: c = mix(c, damp, min(0.6, (w - 0.62) * 2.6))  # damp / algae
        if rng.random() < 0.012: c = (212, 206, 190)              # flaked-off paint
        return c
    return fn


def roof_tiles(seed, base):
    rng = random.Random(seed)
    n, streak = Noise(128, 8, 8, seed + 1), Noise(128, 18, 2, seed + 2)
    def fn(x, y):
        row = y // 16
        xo = (x + (8 if row % 2 else 0)) % 16
        col = (x + (8 if row % 2 else 0)) // 16
        ty = y % 16
        h = ((row * 131 + col * 17 + seed) % 97) / 97.0
        shade = 0.60 + 0.40 * (ty / 15.0)
        if ty >= 14: shade *= 0.5
        if xo == 0: shade *= 0.45
        f = (0.72 + 0.4 * h) * shade * (1 + (n.at(x, y) - 0.5) * 0.35 + (rng.random() - 0.5) * 0.10)
        f *= 1 - max(0.0, streak.at(x, y) - 0.5) * 0.7
        c = mul(base, f)
        if rng.random() < 0.07: c = mix(c, (66, 82, 52), 0.65)    # moss
        elif rng.random() < 0.04: c = mix(c, (150, 150, 140), 0.4)  # lichen
        return c
    return fn


def asphalt(seed):
    rng = random.Random(seed)
    n1, n2 = Noise(128, 8, 8, seed + 1), Noise(128, 32, 32, seed + 2)
    dark = set()
    for _ in range(9):                       # cracks
        x, y = rng.randrange(128), rng.randrange(128)
        a = rng.random() * 6.28
        for _ in range(80):
            a += (rng.random() - 0.5) * 0.9
            x, y = (x + math.cos(a)) % 128, (y + math.sin(a)) % 128
            dark.add((int(x), int(y)))
    patches = []
    for _ in range(2):                       # faint repair patches
        px, py, pw, ph = rng.randrange(128), rng.randrange(128), rng.randrange(14, 28), rng.randrange(10, 20)
        patches.append((px, py, pw, ph))
    puddles = [(rng.randrange(128), rng.randrange(128), rng.randrange(5, 9)) for _ in range(2)]
    def fn(x, y):
        f = 1 + (n1.at(x, y) - 0.5) * 0.26 + (n2.at(x, y) - 0.5) * 0.16 + (rng.random() - 0.5) * 0.16
        if rng.random() < 0.03: f += 0.25
        c = mul((84, 85, 88), f)
        for px, py, pw, ph in patches:
            if (x - px) % 128 < pw and (y - py) % 128 < ph: c = mul(c, 0.88)
        for px, py, r in puddles:
            dx, dy = min((x - px) % 128, (px - x) % 128), min((y - py) % 128, (py - y) % 128)
            d2 = dx * dx + dy * dy
            if d2 < r * r:                   # soft-edged damp spot instead of a hard disc
                t = 1.0 - math.sqrt(d2) / r
                c = mix(c, mix(mul(c, 0.62), (92, 100, 108), 0.25), min(1.0, t * 1.6))
        return mul(c, 0.45) if (x, y) in dark else c
    return fn


def grass(seed):
    rng = random.Random(seed)
    n1, n2, nd = Noise(128, 4, 4, seed + 1), Noise(128, 24, 24, seed + 2), Noise(128, 5, 5, seed + 3)
    def fn(x, y):
        f = 1 + (n1.at(x, y) - 0.5) * 0.40 + (n2.at(x, y) - 0.5) * 0.26 + (rng.random() - 0.5) * 0.22
        c = mul((92, 104, 66), f)
        d = nd.at(x, y)
        if d > 0.6: c = mix(c, mul((108, 92, 66), f), min(1.0, (d - 0.6) * 2.8))   # bare mud
        return c
    return fn


def gravel(seed):
    rng = random.Random(seed)
    n1, nm = Noise(128, 6, 6, seed + 1), Noise(128, 4, 4, seed + 2)
    def fn(x, y):
        f = 1 + (n1.at(x, y) - 0.5) * 0.24 + (rng.random() - 0.5) * 0.46
        if rng.random() < 0.09: f *= 0.58
        c = mul((130, 120, 102), f)
        m = nm.at(x, y)
        return mix(c, (84, 72, 58), min(0.7, (m - 0.55) * 2.2)) if m > 0.55 else c  # mud
    return fn


def window(lit):
    rng = random.Random(7)
    grime = Noise(64, 4, 4, 77)
    def fn(x, y):
        frame = x < 4 or x >= 60 or y < 4 or y >= 60
        bar = (30 <= x <= 33) or (30 <= y <= 33)
        if frame or bar:
            c = (204, 200, 188) if (x + y) % 11 else (176, 172, 162)
            return mix(c, (110, 110, 100), 0.25 * grime.at(x, y)) if rng.random() > 0.05 else (150, 146, 134)
        if lit:
            c = (226, 184, 96)
            if x < 16 or x > 47: c = (164, 118, 70)           # curtains
            return mul(c, 0.88 + (rng.random() - 0.5) * 0.1)
        g = (1 - (x + y) / 128.0) * 0.35                       # weak reflection
        c = mul((30, 36, 42), 1 + g + (rng.random() - 0.5) * 0.12)
        return mix(c, (70, 76, 70), 0.35 * grime.at(x, y))     # dirty glass
    return fn


def planks(seed, base, plank=8):
    rng = random.Random(seed)
    n, rot = Noise(64, 2, 16, seed + 1), Noise(64, 5, 5, seed + 2)
    def fn(x, y):
        i = x // plank
        shade = 0.75 + 0.4 * (((i * 53 + seed) % 31) / 31.0)
        f = shade * (1 + (n.at(x % 64, y % 64) - 0.5) * 0.34 + (rng.random() - 0.5) * 0.10)
        if x % plank == 0: f *= 0.4
        c = mul(base, f)
        r = rot.at(x, y)
        return mix(c, (86, 94, 74), min(0.5, (r - 0.55) * 1.8)) if r > 0.55 else c   # damp / mould
    return fn


def bark(seed):
    rng = random.Random(seed)
    n = Noise(64, 8, 2, seed + 1)
    def fn(x, y):
        f = 0.55 + 0.8 * n.at(x, y) + (rng.random() - 0.5) * 0.15
        if rng.random() < 0.04: f *= 0.5
        return mul((62, 50, 40), f)
    return fn


def foliage(seed):
    rng = random.Random(seed)
    n = Noise(64, 12, 12, seed + 1)
    def fn(x, y):
        f = 1 + (n.at(x, y) - 0.5) * 0.5
        c = mul((26, 46, 36), f)
        r = rng.random()
        if r < 0.10: return (52, 82, 58)
        if r > 0.86: return (14, 26, 22)
        return c
    return fn


def brick(seed):
    rng = random.Random(seed)
    soot = Noise(64, 4, 4, seed + 1)
    def fn(x, y):
        row = y // 8
        xo = (x + (8 if row % 2 else 0)) % 16
        if y % 8 == 0 or xo == 0: return (150, 146, 136)
        h = (((row * 7 + (x + (8 if row % 2 else 0)) // 16 * 13) + seed) % 23) / 23.0
        c = mul((124, 60, 48), 0.75 + 0.4 * h + (rng.random() - 0.5) * 0.12)
        return mul(c, 0.55 + 0.45 * (1 - soot.at(x, y)))
    return fn


def door():
    rng = random.Random(11)
    n = Noise(64, 3, 12, 12)
    def fn(x, y):
        i = x // 8
        f = (0.74 + 0.4 * (((i * 37) % 29) / 29.0)) * (1 + (rng.random() - 0.5) * 0.12) * (0.8 + n.at(x % 64, y % 64) * 0.4)
        if x % 8 == 0: f *= 0.4
        if 50 <= x <= 54 and 64 <= y <= 67: return (176, 164, 96)   # handle
        return mul((76, 52, 38), f)
    return fn


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    spec = [
        ("plaster_cream", 128, 128, plaster(100, (188, 180, 156)), 100),
        ("plaster_grey", 128, 128, plaster(200, (150, 150, 142)), 200),
        ("roof_tiles_red", 128, 128, roof_tiles(300, (128, 62, 46)), 300),
        ("roof_tiles_brown", 128, 128, roof_tiles(310, (88, 62, 50)), 310),
        ("asphalt", 128, 128, asphalt(400), 400),
        ("grass", 128, 128, grass(500), 500),
        ("gravel", 128, 128, gravel(600), 600),
        ("window_dark", 64, 64, window(False), 7),
        ("window_lit", 64, 64, window(True), 7),
        ("door_wood", 64, 128, door(), 11),
        ("fence_planks", 64, 64, planks(700, (150, 140, 120)), 700),
        ("bark", 64, 64, bark(800), 800),
        ("foliage", 64, 64, foliage(900), 900),
        ("brick", 64, 64, brick(950), 950),
    ]
    entries = []
    for name, w, h, fn, seed in spec:
        build(name, w, h, fn)
        entries.append({"file": f"art/textures/{name}.png", "size": [w, h], "source": "procedural",
                        "generator": "tools/art/gen_textures.py", "seed": seed,
                        "license": "original work, generated by project code; no third-party image data",
                        "created": "2026-11-07"})
    (ROOT / "art/manifest.json").write_text(json.dumps({"images": entries}, indent=2, ensure_ascii=False), encoding="utf-8")
    print("textures:", len(entries), "->", OUT)


if __name__ == "__main__":
    main()
