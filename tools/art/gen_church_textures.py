"""Procedural textures for the church (kosciol, Linia): white lime plaster, dark standing-seam roof, field stone,
timber, clock face, arched windows, doors, the black cross, the open belfry, the balustrade.

Original work generated by this script. The reference photos in `src/key buildings/church/` were used ONLY to decide
shapes, proportions and the colour palette: no pixel of any photo is copied (the rights to the photos are not known).
Entries are merged into art/manifest.json.

Usage: python3 tools/art/gen_church_textures.py
"""
import json, math, pathlib, random, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import gen_textures as G
from gen_textures import Noise, mul, mix

WALL = (226, 222, 214)          # lime-washed plaster, slightly warm


def plaster_white(seed):
    rng = random.Random(seed)
    n1, n2, streak = Noise(128, 4, 4, seed + 1), Noise(128, 16, 16, seed + 2), Noise(128, 18, 2, seed + 3)
    def fn(x, y):
        f = 1 + (n1.at(x, y) - 0.5) * 0.12 + (n2.at(x, y) - 0.5) * 0.08 + (rng.random() - 0.5) * 0.04
        f *= 1 - max(0.0, streak.at(x, y) - 0.6) * 0.18
        return mul(WALL, f)
    return fn


def roof_metal(seed):
    """Dark standing-seam sheet metal: a raised seam every 32 px (0.5 m at a 2 m tile), sheet-to-sheet tone changes."""
    rng = random.Random(seed)
    n, streak = Noise(128, 6, 6, seed + 1), Noise(128, 24, 2, seed + 2)
    def fn(x, y):
        sheet = ((x // 32) * 37 + seed) % 11 / 11.0
        f = (0.86 + 0.28 * sheet) * (1 + (n.at(x, y) - 0.5) * 0.30 + (rng.random() - 0.5) * 0.05)
        f *= 1 - max(0.0, streak.at(x, y) - 0.55) * 0.4
        sx = x % 32
        if sx == 0: f *= 1.35
        elif sx == 1: f *= 0.65
        elif sx == 2: f *= 0.8
        c = mul((84, 91, 89), f)
        if rng.random() < 0.01: c = mix(c, (120, 80, 60), 0.5)          # rust speck
        return c
    return fn


def fieldstone(seed):
    """Irregular field stones with dark mortar joints (Voronoi cells, tiling)."""
    rng = random.Random(seed)
    seeds = [(rng.random() * 128, rng.random() * 128, rng.random()) for _ in range(34)]
    n = Noise(128, 8, 8, seed + 1)
    def fn(x, y):
        best = second = 1e9
        bid = 0.0
        for sx, sy, sid in seeds:
            dx = min(abs(x - sx), 128 - abs(x - sx)); dy = min(abs(y - sy), 128 - abs(y - sy))
            d = math.hypot(dx, dy)
            if d < best: second, best, bid = best, d, sid
            elif d < second: second = d
        if second - best < 2.6: return (96, 92, 84)                     # mortar
        f = (0.72 + 0.5 * bid) * (1 + (n.at(x, y) - 0.5) * 0.3 + (rng.random() - 0.5) * 0.1)
        warm = 0.5 + 0.5 * ((bid * 7) % 1.0)
        return mul(mix((120, 114, 106), (136, 112, 90), warm), f)
    return fn


def timber(seed):
    rng = random.Random(seed)
    grain, dark = Noise(64, 3, 18, seed + 1), Noise(64, 2, 7, seed + 2)
    def fn(x, y):
        f = 0.7 + 0.6 * grain.at(x, y) + (rng.random() - 0.5) * 0.08
        f *= 0.85 + 0.3 * dark.at(x, y)
        return mul((136, 78, 42), f)
    return fn


def _arch_inside(x, y, w, m, extra=0):
    """Rectangle with a semicircular top: margin m (+ extra), True when the pixel is inside."""
    left, right = m + extra, w - 1 - m - extra
    r = (right - left + 1) / 2.0
    top_cy = m + extra + r
    if x < left or x > right: return False
    if y < top_cy: return math.hypot(x - (left + r - 0.5), y - top_cy) <= r
    return True


def arch_window(kind):
    rng = random.Random(21 if kind == "white" else 22)
    grime = Noise(64, 4, 4, 5)
    def fn(x, y, w=64, h=128):
        if not _arch_inside(x, y, w, 4): return mul(WALL, 1 + (rng.random() - 0.5) * 0.04)
        if not _arch_inside(x, y, w, 4, 5):                               # frame
            return (240, 238, 232) if kind == "white" else (118, 62, 44)
        if kind == "louvre":
            return (112, 58, 46) if (y % 6) < 4 else (46, 24, 20)
        c = mul((42, 56, 82), 0.9 + 0.3 * (1 - y / h) + (rng.random() - 0.5) * 0.08)
        if abs(x - w / 2) < 1.2 or (abs(y - h * 0.62) < 1.2 and kind == "white"): c = (238, 236, 230)   # bars
        return mix(c, (70, 78, 80), 0.25 * grime.at(x, y))
    return fn


def window_grid():
    rng = random.Random(23)
    def fn(x, y, w=64, h=128):
        border = x < 5 or x > w - 6 or y < 5 or y > h - 6
        bar = x % 16 in (0, 1) or y % 20 in (0, 1)
        if border or bar: return mul((146, 84, 44), 0.85 + rng.random() * 0.3)
        return mul((40, 52, 70), 0.85 + (1 - y / h) * 0.4 + (rng.random() - 0.5) * 0.06)
    return fn


def door_green():
    rng = random.Random(24)
    stone = Noise(64, 8, 16, 7)
    def fn(x, y, w=64, h=128):
        if not _arch_inside(x, y, w, 0):
            return mul((118, 108, 94), 0.8 + 0.4 * stone.at(x, y))          # stone surround
        if not _arch_inside(x, y, w, 0, 5): return mul((112, 104, 90), 0.85 + 0.3 * stone.at(x, y))
        if y < h * 0.34:                                                   # fanlight
            return mul((40, 56, 74), 0.8 + (rng.random() - 0.5) * 0.1) if (x + y) % 9 else (210, 206, 196)
        c = mul((36, 60, 44), 0.85 + (rng.random() - 0.5) * 0.12)
        if abs(x - w / 2) < 1.2: c = mul(c, 0.4)                           # leaves meet here
        if 8 < x < w - 8 and (int(h * 0.42) < y < int(h * 0.62) or int(h * 0.68) < y < h - 8) and abs(x - w / 2) > 3:
            c = mul(c, 0.8)                                                # panels
        if 26 <= x <= 28 and 82 <= y <= 90: return (196, 176, 90)         # handle
        return c
    return fn


def cross_black():
    def fn(x, y, w=64, h=128):
        if 29 <= x <= 34 and 6 <= y <= 120: return (22, 22, 24)
        if 12 <= x <= 51 and 38 <= y <= 45: return (22, 22, 24)
        return mul(WALL, 1 - 0.02 * ((x * 7 + y * 3) % 5))
    return fn


def clock_face():
    def fn(x, y, w=64, h=64):
        cx = cy = 31.5
        d = math.hypot(x - cx, y - cy)
        if d > 31: return mul(WALL, 0.95)
        if d > 27: return (236, 232, 224)                                  # white rim
        c = (218, 178, 74)                                                 # gold dial
        ang = math.atan2(y - cy, x - cx)
        if 22 < d < 26:
            for k in range(12):
                a = k * math.pi / 6
                if abs(((ang - a + math.pi) % (2 * math.pi)) - math.pi) < 0.06: return (40, 34, 24)
        for hand_ang, length, thick in ((math.radians(-60), 15, 1.6), (math.radians(30), 22, 1.1)):
            hx, hy = math.cos(hand_ang), math.sin(hand_ang)
            t = max(0.0, min(length, (x - cx) * hx + (y - cy) * hy))
            if math.hypot(x - (cx + hx * t), y - (cy + hy * t)) < thick: return (30, 26, 22)
        return c
    return fn


def belfry_arches():
    rng = random.Random(25)
    def fn(x, y, w=128, h=64):
        for cx in (22, 64, 106):
            lx = x - (cx - 13)
            if 0 <= lx < 26 and y >= 8 and y < 54:
                inside = True
                if y < 8 + 13:
                    inside = math.hypot(lx - 12.5, y - 21) <= 13
                if inside:
                    if abs(lx - 12.5) < 4.5 and 28 < y < 48 and math.hypot((lx - 12.5) / 4.5, (y - 38) / 10) < 1:
                        return (196, 150, 60)                              # a bell in the dark
                    return mul((26, 26, 28), 0.8 + rng.random() * 0.4)
        if y > 54: return (236, 232, 224)                                  # sill / cornice
        return mul(WALL, 1 - 0.02 * ((x * 5 + y * 3) % 5))
    return fn


def balustrade():
    def fn(x, y, w=128, h=32):
        if y < 4 or y >= h - 5: return (238, 236, 230)                     # rails
        if x % 10 in (3, 4, 5, 6): return (236, 233, 226)                  # balusters
        return (150, 156, 162)                                             # gaps (sky and wall behind)
    return fn


def main():
    G.OUT.mkdir(parents=True, exist_ok=True)
    spec = [
        ("c_plaster", 128, 128, plaster_white(1100), 1100),
        ("c_roof_metal", 128, 128, roof_metal(1200), 1200),
        ("c_fieldstone", 128, 128, fieldstone(1300), 1300),
        ("c_timber", 64, 64, timber(1400), 1400),
        ("c_clock", 64, 64, clock_face(), 0),
        ("c_arch_white", 64, 128, arch_window("white"), 21),
        ("c_arch_louvre", 64, 128, arch_window("louvre"), 22),
        ("c_arch_brown", 64, 128, arch_window("brown"), 22),
        ("c_window_grid", 64, 128, window_grid(), 23),
        ("c_door_green", 64, 128, door_green(), 24),
        ("c_cross", 64, 128, cross_black(), 0),
        ("c_belfry", 128, 64, belfry_arches(), 25),
        ("c_balustrade", 128, 32, balustrade(), 0),
    ]
    manifest_path = G.ROOT / "art/manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8")) if manifest_path.exists() else {"images": []}
    images = [e for e in manifest["images"] if not e["file"].split("/")[-1].startswith("c_")]
    for name, w, h, fn, seed in spec:
        G.build(name, w, h, fn)
        images.append({"file": f"art/textures/{name}.png", "size": [w, h], "source": "procedural",
                       "generator": "tools/art/gen_church_textures.py", "seed": seed,
                       "reference": "src/key buildings/church/ (shapes, proportions and palette only; no pixels copied)",
                       "license": "original work, generated by project code; no third-party image data",
                       "created": "2026-11-07"})
    manifest["images"] = images
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")
    print("church textures:", len(spec), "| manifest entries:", len(images))


if __name__ == "__main__":
    main()
